import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { initializeApp } from 'firebase-admin/app';
import { getFirestore, Timestamp } from 'firebase-admin/firestore';
import { createBackend } from '../src/store.mjs';
import { defaults } from '../src/domain.mjs';
const ready = process.env.FIRESTORE_EMULATOR_HOST === '127.0.0.1:8080' && process.env.GCLOUD_PROJECT === 'demo-bepxinh';
test('AI backend: ownership, config roles, encrypted key, retry, quota, hidden recipes and concurrent calls', { skip: !ready }, async () => {
  initializeApp({projectId:'demo-bepxinh'}, 'ai-integration');
  const db = getFirestore((await import('firebase-admin/app')).getApp('ai-integration'));
  let now = Date.UTC(2026,10,17), calls = 0, waiting, hideDuringResponse = false, echoKey = false, capturedHistory;
  const provider = async (_, key, __, history, ___, candidates) => {
    assert.equal(key, 'emulator-test-key-123456'); calls++; capturedHistory = history;
    if (waiting) await waiting;
    if (hideDuringResponse) await db.doc('recipes/r_ai_fixture').update({status:'hidden'});
    return JSON.stringify({reply:echoKey ? key : 'Bạn có thể thử món này.',recipeIds:candidates.length ? ['r_ai_fixture','invented'] : []});
  };
  const backend = createBackend(db, {master:()=>Buffer.alloc(32,7).toString('base64'),provider,modelProvider:async key=>{assert.equal(key,'emulator-test-key-123456');return [{id:'gemini-test-flash',name:'gemini-test-flash'}];},now:()=>now});
  for (const [uid,role] of [['ai_admin','admin'],['ai_moderator','moderator'],['ai_alice','user'],['ai_bob','user']]) await db.doc(`users/${uid}`).set({id:uid,role,status:'active'});
  await db.doc('recipes/r_ai_fixture').set({status:'approved',submittedAt:Timestamp.fromMillis(now),content:{title:'Trứng chiên',cover:{id:'cover',name:'cover.png',url:'https://res.cloudinary.com/ddqouziau/image/upload/v1/test.png',publicId:'test'},ingredients:[{name:'Trứng'}],preparationMinutes:5,cookingMinutes:10,difficulty:'easy'}});
  await assert.rejects(backend.adminConfig('ai_moderator'),e=>e.status===403);
  await assert.rejects(backend.adminModels('ai_moderator',{apiKey:'emulator-test-key-123456'}),e=>e.status===403);
  await assert.rejects(backend.adminModels('ai_admin',{apiKey:''}),e=>e.code==='key_required');
  await assert.rejects(backend.adminModels('ai_admin',{apiKey:'emulator-test-key-123456',uid:'other'}),e=>e.status===400);
  assert.deepEqual((await backend.adminModels('ai_admin',{apiKey:'emulator-test-key-123456'})).models.map(m=>m.id),['gemini-test-flash']);
  assert.equal((await db.doc('_ai_private/config').get()).exists,false);
  now+=60000;
  const config = await backend.saveConfig('ai_admin',{...defaults,enabled:true,dailyLimit:10,apiKey:'emulator-test-key-123456'});
  assert.equal(config.hasKey,true); assert.ok(!JSON.stringify(config).includes('emulator-test-key'));
  assert.ok(!JSON.stringify((await db.doc('_ai_private/config').get()).data()).includes('emulator-test-key'));
  await assert.rejects(backend.saveConfig('ai_admin',{...defaults,enabled:false,apiKey:''}),e=>e.code==='config_changed');
  const one = {requestId:randomBytes(16).toString('hex'),message:'Gợi ý trứng chiên'};
  const answer = await backend.chat('ai_alice',one), count = calls;
  assert.deepEqual(answer.assistant.recipes.map(r=>r.id),['r_ai_fixture']);
  assert.deepEqual(await backend.chat('ai_alice',one),answer); assert.equal(calls,count);
  await assert.rejects(backend.chat('ai_alice',{...one,message:'changed'}),e=>e.code==='request_changed');
  assert.equal((await backend.history('ai_bob')).length,0);
  assert.deepEqual((await backend.history('ai_alice')).map(m=>m.role),['user','assistant']);
  now += 60000;
  await backend.chat('ai_alice',{requestId:randomBytes(16).toString('hex'),message:'Cách lưu món?'});
  assert.equal(capturedHistory.length,2);
  await db.doc('users/ai_bob').update({status:'locked'});
  await assert.rejects(backend.history('ai_bob'),e=>e.status===403);
  await assert.rejects(backend.chat('ai_bob',one),e=>e.status===403);
  now += 60000; hideDuringResponse = true;
  const hidden = await backend.chat('ai_alice',{requestId:randomBytes(16).toString('hex'),message:'Gợi ý món'});
  assert.equal(hidden.assistant.recipes.length,0); hideDuringResponse = false;
  now += 60000;
  let release; waiting = new Promise(r=>release=r);
  const parallelId = randomBytes(16).toString('hex'), first = backend.chat('ai_alice',{requestId:parallelId,message:'Đang hỏi'});
  for(let i=0;i<100;i++){if((await db.doc(`_ai_requests/ai_alice_${parallelId}`).get()).data()?.status==='processing')break;await new Promise(r=>setTimeout(r,10));}
  await assert.rejects(backend.chat('ai_alice',{requestId:parallelId,message:'Đang hỏi'}),e=>e.code==='processing');
  await assert.rejects(backend.chat('ai_alice',{requestId:randomBytes(16).toString('hex'),message:'Câu khác'}),e=>e.code==='processing');
  release(); await first; waiting = null;
  now += 60000; echoKey = true;
  await assert.rejects(backend.chat('ai_alice',{requestId:randomBytes(16).toString('hex'),message:'Kiểm tra phản hồi'}),e=>e.code==='provider_unsafe' && !e.message.includes('emulator-test-key'));
  echoKey = false;
  now += 60000;
  const historyBeforeLock = (await backend.history('ai_alice')).length, callsBeforeLock = calls;
  waiting = new Promise(r=>release=r);
  const lockedTurn = backend.chat('ai_alice',{requestId:randomBytes(16).toString('hex'),message:'Đang trả lời khi bị khóa'});
  for(let i=0;i<100&&calls===callsBeforeLock;i++) await new Promise(r=>setTimeout(r,10));
  assert.ok(calls>callsBeforeLock,'Provider started before account was locked');
  await db.doc('users/ai_alice').update({status:'locked'});
  release();
  await assert.rejects(lockedTurn,e=>e.status===403);
  waiting=null;
  await db.doc('users/ai_alice').update({status:'active'});
  assert.equal((await backend.history('ai_alice')).length,historyBeforeLock);
  const latestConfig = await backend.adminConfig('ai_admin');
  const {hasKey: _, ...editable} = latestConfig;
  await backend.saveConfig('ai_admin',{...editable,dailyLimit:1,apiKey:''});
  await db.doc('users/ai_bob').update({status:'active'});
  await backend.chat('ai_bob',{requestId:randomBytes(16).toString('hex'),message:'Làm sao lưu món?'});
  await assert.rejects(backend.chat('ai_bob',{requestId:randomBytes(16).toString('hex'),message:'Câu tiếp theo'}),e=>e.code==='quota');
  const day = new Date(now + 7 * 3600000).toISOString().slice(0,10);
  await assert.rejects(backend.adminStats('ai_moderator'),e=>e.status===403);
  await assert.rejects(backend.adminStats('ai_alice'),e=>e.status===403);
  const stats = await backend.adminStats('ai_admin');
  assert.equal(stats.daily.length,7); assert.equal(stats.totals.requests,7);
  assert.equal(stats.totals.completed,5); assert.equal(stats.totals.failed,2);
  assert.equal(stats.totals.users,2); assert.equal(stats.totals.attempts,7);
  assert.ok(!JSON.stringify(stats).includes('emulator-test-key'));
  assert.ok(!JSON.stringify(stats).includes('ai_alice'));
  assert.ok(!JSON.stringify(stats).includes('Gợi ý'));
  await db.doc(`_ai_limits/project_${day}`).update({count:500});
  await assert.rejects(backend.chat('ai_alice',{requestId:randomBytes(16).toString('hex'),message:'Quá hạn mức chung'}),e=>e.code==='project_quota');
  await db.doc('users/ai_alice').update({status:'locked'});
  await assert.rejects(backend.history('ai_alice'),e=>e.status===403);
  console.log('AI integration ownership/config/cached retry/hidden-source/concurrency checks passed (demo only).');
  await db.doc('_ai_private/config').delete();
});
